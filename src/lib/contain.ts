// Phase 4 of the identity access plan: act on what User lookup found, without Federation 360 writing anything itself.
//
//  - Remediation 360 hand-off links: Disable user everywhere, Remove from one app, and device containment open its
//    Offboard or Emergency page with the request filled in. Remediation 360 does the writes as the signed-in operator and audits them.
//  - Contain runbook: the same steps as PowerShell for the operator to run themselves, What-if unless -Run is given.
//  - Verify: compare the read before and after, so the person can see the exposure close.
//  - Live refresh capture: token refreshes recorded by the Federation 360 Capture extension, per app.
import { decodeJwt } from "./jwt";
import type { FlowCapture } from "./flow";
import type { UserAccessSnapshot } from "./lookup";

export const R360_DEFAULT_URL = "http://localhost:3660";
const GUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const MAX_APPS = 50;

export interface ContainApp {
  spId: string;
  name: string;
}

/** Cleans the Remediation 360 address the person typed: http(s) origin only, no path, no credentials. */
export function r360Base(url: string): string {
  try {
    const u = new URL(url.trim() || R360_DEFAULT_URL);
    if (u.protocol !== "http:" && u.protocol !== "https:") return R360_DEFAULT_URL;
    if (u.protocol === "http:" && u.hostname !== "localhost" && u.hostname !== "127.0.0.1") return R360_DEFAULT_URL;
    return u.origin;
  } catch {
    return R360_DEFAULT_URL;
  }
}

const appParams = (apps: ContainApp[]) =>
  apps
    .filter((a) => GUID.test(a.spId))
    .slice(0, MAX_APPS)
    .map((a) => `app=${encodeURIComponent(`${a.spId.toLowerCase()}:${a.name.slice(0, 120)}`)}`);

/** Remediation 360's Offboard page with the request filled in. The person still signs in, elevates and clicks Run request there. */
export function r360OffboardUrl(base: string, type: "disable" | "remove", upn: string, apps: ContainApp[]): string {
  const list = type === "remove" ? apps.slice(0, 1) : apps;
  const q = [`user=${encodeURIComponent(upn)}`, ...appParams(list), "from=federation-360"].join("&");
  return `${r360Base(base)}/#offboard/${type}?${q}`;
}

/** Remediation 360's Emergency page with the device name filled in and Isolate chosen; a second person approves there. */
export function r360DeviceUrl(base: string, device: string): string {
  return `${r360Base(base)}/#emergency/device?name=${encodeURIComponent(device)}&action=isolate`;
}

const psq = (s: string) => `'${s.replace(/'/g, "''")}'`;

/**
 * PowerShell that disables the person, revokes sessions and runs Provision on demand in each SCIM app, then re-reads the
 * account. Without -Run every change is only described (What-if). Uses the Microsoft Graph PowerShell SDK, delegated.
 */
export function containRunbook(opts: { upn: string; tenantId?: string; apps: ContainApp[]; generatedAt?: Date }): string {
  const apps = opts.apps.filter((a) => GUID.test(a.spId)).slice(0, MAX_APPS);
  const tid = opts.tenantId && GUID.test(opts.tenantId) ? opts.tenantId : "";
  const appLines = apps.length ? apps.map((a) => `    @{ Id = ${psq(a.spId.toLowerCase())}; Name = ${psq(a.name || a.spId)} }`).join("\n") : "";
  return `<#
.SYNOPSIS
  Contain one person: disable the account, revoke sign-in sessions, push the disable to their SCIM apps now
  (Provision on demand), then re-read the account. Generated by Federation 360 User lookup${opts.generatedAt ? ` on ${opts.generatedAt.toISOString().slice(0, 10)}` : ""}.

.DESCRIPTION
  Without -Run, nothing changes: every step is shown as What if. Run it once like that, read the output, then run it
  again with -Run. Federation 360 itself never writes; this script runs with YOUR sign-in and YOUR Entra role:
    - User Administrator to disable an ordinary user (Privileged Authentication Administrator for an admin account)
    - Application Administrator or Cloud Application Administrator for Provision on demand
  Delegated permissions asked for: User.EnableDisableAccount.All, User.RevokeSessions.All, User.Read.All,
  Synchronization.ReadWrite.All.

  Access tokens already issued keep working until they expire (up to 90 minutes), except in Microsoft 365 services that
  support Continuous Access Evaluation. Apps that keep their own session keep it until they hear from SCIM or it ends.
  Afterwards, open User lookup and click Verify with a fresh read.

.EXAMPLE
  .\\Contain-F360User.ps1          # What if: shows each step
  .\\Contain-F360User.ps1 -Run     # does it
#>
#Requires -Version 7.2
[CmdletBinding(SupportsShouldProcess)]
param(
    [switch]$Run,
    [string]$TenantId = ${psq(tid)},
    [string]$User = ${psq(opts.upn)}
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
if (-not $Run) { $WhatIfPreference = $true; Write-Host 'What-if mode: nothing will change. Run again with -Run to do it.' -ForegroundColor Yellow }

$apps = @(
${appLines}
)

if (-not (Get-Module -ListAvailable Microsoft.Graph.Authentication)) { throw 'Install-Module Microsoft.Graph.Authentication -Scope CurrentUser first.' }
$connect = @{ Scopes = @('User.Read.All', 'User.EnableDisableAccount.All', 'User.RevokeSessions.All', 'Synchronization.ReadWrite.All'); NoWelcome = $true; ContextScope = 'Process' }
if ($TenantId) { $connect.TenantId = $TenantId }
Connect-MgGraph @connect

$u = Invoke-MgGraphRequest -Method GET -Uri "/v1.0/users/$([uri]::EscapeDataString($User))?\`$select=id,displayName,userPrincipalName,accountEnabled,signInSessionsValidFromDateTime"
Write-Host "Person: $($u.displayName) <$($u.userPrincipalName)>, enabled: $($u.accountEnabled), sessions valid from: $($u.signInSessionsValidFromDateTime)"
$started = Get-Date
$times = [ordered]@{ Started = $started.ToString('o') }

if ($PSCmdlet.ShouldProcess($u.userPrincipalName, 'Disable the account')) {
    Invoke-MgGraphRequest -Method PATCH -Uri "/v1.0/users/$($u.id)" -Body @{ accountEnabled = $false } | Out-Null
    $times.Disabled = (Get-Date).ToString('o'); Write-Host 'Account disabled.'
}
if ($PSCmdlet.ShouldProcess($u.userPrincipalName, 'Revoke every sign-in session (refresh tokens stop working)')) {
    Invoke-MgGraphRequest -Method POST -Uri "/v1.0/users/$($u.id)/revokeSignInSessions" | Out-Null
    $times.Revoked = (Get-Date).ToString('o'); Write-Host 'Sessions revoked.'
}

foreach ($a in $apps) {
    $jobs = @((Invoke-MgGraphRequest -Method GET -Uri "/v1.0/servicePrincipals/$($a.Id)/synchronization/jobs").value)
    if (-not $jobs) { Write-Host "$($a.Name): no SCIM provisioning job; its own session decides when access ends."; continue }
    foreach ($j in $jobs) {
        $schema = Invoke-MgGraphRequest -Method GET -Uri "/v1.0/servicePrincipals/$($a.Id)/synchronization/jobs/$($j.id)/schema"
        $rule = @($schema.synchronizationRules | Where-Object { @($_.objectMappings | Where-Object { $_.sourceObjectName -eq 'User' }).Count })[0]
        if (-not $rule) { Write-Warning "$($a.Name): no user rule in job $($j.id)"; continue }
        if ($PSCmdlet.ShouldProcess("$($a.Name) (job $($j.templateId))", 'Provision on demand (sends the disable now)')) {
            $body = @{ parameters = @(@{ ruleId = $rule.id; subjects = @(@{ objectId = $u.id; objectTypeName = 'User' }) }) }
            $r = Invoke-MgGraphRequest -Method POST -Uri "/v1.0/servicePrincipals/$($a.Id)/synchronization/jobs/$($j.id)/provisionOnDemand" -Body $body
            $times["SCIM $($a.Name)"] = (Get-Date).ToString('o')
            Write-Host "$($a.Name): $($r.value)"
        }
    }
}

$after = Invoke-MgGraphRequest -Method GET -Uri "/v1.0/users/$($u.id)?\`$select=accountEnabled,signInSessionsValidFromDateTime"
Write-Host "Re-read: enabled $($after.accountEnabled), sessions valid from $($after.signInSessionsValidFromDateTime)"
$times.GetEnumerator() | ForEach-Object { '{0,-30} {1}' -f $_.Key, $_.Value }
`;
}

export interface ReadChange {
  what: string;
  before: string;
  after: string;
  good: boolean;
}

/** What changed between two reads of the same person: the proof that containment worked, or didn't. */
export function compareReads(before: UserAccessSnapshot, after: UserAccessSnapshot): ReadChange[] {
  const out: ReadChange[] = [];
  const yesNo = (b: boolean) => (b ? "Enabled" : "Disabled");
  out.push({ what: "Account", before: yesNo(before.user.enabled), after: yesNo(after.user.enabled), good: !after.user.enabled });
  const vb = before.user.sessionsValidFrom ?? "";
  const va = after.user.sessionsValidFrom ?? "";
  out.push({ what: "Sessions valid from", before: vb ? new Date(vb).toLocaleString() : "not read", after: va ? new Date(va).toLocaleString() : "not read", good: !!va && (!vb || Date.parse(va) > Date.parse(vb)) });
  const key = (a: { spId: string; via: string; group?: string }) => `${a.spId}|${a.via}|${a.group ?? ""}`;
  const afterKeys = new Set(after.assignments.map(key));
  const gone = before.assignments.filter((a) => !afterKeys.has(key(a)));
  out.push({ what: "App assignments", before: String(before.assignments.length), after: String(after.assignments.length), good: after.assignments.length <= before.assignments.length });
  for (const g of gone) out.push({ what: `Removed: ${g.app}`, before: g.via === "direct" ? "Assigned directly" : `Through ${g.group ?? "a group"}`, after: "Gone", good: true });
  out.push({ what: "Consent grants", before: String(before.grants.length), after: String(after.grants.length), good: after.grants.length <= before.grants.length });
  out.push({ what: "Devices enabled", before: String(before.devices.filter((d) => d.enabled).length), after: String(after.devices.filter((d) => d.enabled).length), good: after.devices.filter((d) => d.enabled).length <= before.devices.filter((d) => d.enabled).length });
  return out;
}

export interface LiveRefresh {
  at: number;
  clientId: string;
  scope: string;
  /** Lifetime of the access token that came back, in minutes, when it is a readable JWT. */
  lifetimeMin?: number;
  error?: string;
}

export interface LiveRefreshApp {
  clientId: string;
  count: number;
  /** Median minutes between refreshes seen in this browser. */
  medianGapMin?: number;
  lifetimeMin?: number;
  last: number;
  failures: number;
}

/** Token refreshes (grant_type=refresh_token) recorded by the Capture extension, newest first, and grouped per app. */
export function liveRefreshes(captures: FlowCapture[]): { events: LiveRefresh[]; apps: LiveRefreshApp[] } {
  const events: LiveRefresh[] = [];
  for (const c of captures) {
    for (const s of c.steps ?? []) {
      if (s.params?.grant_type !== "refresh_token" || !s.at) continue;
      let lifetimeMin: number | undefined;
      const at = s.tokens?.find((t) => t.name === "access_token")?.value;
      if (at) {
        try {
          const p = decodeJwt(at).payload as Record<string, unknown>;
          if (typeof p.exp === "number" && typeof p.iat === "number") lifetimeMin = Math.round((p.exp - p.iat) / 60);
        } catch {
          /* opaque token */
        }
      }
      events.push({ at: Date.parse(s.at), clientId: s.params.client_id ?? "unknown", scope: s.params.scope ?? "", lifetimeMin, error: s.error?.code });
    }
  }
  events.sort((a, b) => b.at - a.at);
  const by = new Map<string, LiveRefresh[]>();
  for (const e of events) by.set(e.clientId, [...(by.get(e.clientId) ?? []), e]);
  const apps: LiveRefreshApp[] = [...by.entries()].map(([clientId, list]) => {
    const times = list.filter((e) => !e.error).map((e) => e.at).sort((a, b) => a - b);
    const gaps = times.slice(1).map((t, i) => (t - times[i]) / 60000).sort((a, b) => a - b);
    const lifetimes = list.map((e) => e.lifetimeMin).filter((x): x is number => x !== undefined);
    return {
      clientId,
      count: list.length,
      medianGapMin: gaps.length ? Math.round(gaps[Math.floor(gaps.length / 2)]) : undefined,
      lifetimeMin: lifetimes.length ? Math.max(...lifetimes) : undefined,
      last: list[0].at,
      failures: list.filter((e) => e.error).length,
    };
  });
  apps.sort((a, b) => b.last - a.last);
  return { events, apps };
}

