// Contain and clean up after an identity incident found on Investigate. Federation 360 still writes nothing:
//  - cleanupRunbook: PowerShell the analyst runs (What-if unless -Run) to remove what the attacker added: MFA methods
//    registered during the incident, consent grants to the apps consented during it, and the forwarding or hiding
//    inbox rules found. It revokes sessions again at the end.
//  - verifyContainment: a fresh, read-only Graph read that shows whether containment took: is the account disabled,
//    were sessions revoked after the containment time, and has anyone signed in successfully since.
import { LogsError, classifyGraphError } from "./entraLogs";

const psq = (s: string) => `'${s.replace(/'/g, "''")}'`;
const GUID = /^[0-9a-f]{8}-([0-9a-f]{4}-){3}[0-9a-f]{12}$/i;

export function cleanupRunbook(opts: { upn: string; tenantId?: string; since: number; apps: string[]; inboxRules: string[]; caseId: string; generatedAt?: Date }): string {
  const tid = opts.tenantId && GUID.test(opts.tenantId) ? opts.tenantId : "";
  const list = (xs: string[]) => (xs.length ? xs.slice(0, 50).map((x) => `    ${psq(x)}`).join("\n") : "");
  return `<#
.SYNOPSIS
  Clean up after incident ${opts.caseId}: remove what the attacker added to ${opts.upn}, then revoke sessions again.
  Generated by Federation 360 Investigate${opts.generatedAt ? ` on ${opts.generatedAt.toISOString().slice(0, 10)}` : ""}.

.DESCRIPTION
  Without -Run, nothing changes: every step is shown as What if. Read the output, then run it again with -Run.
  Federation 360 never writes; this runs with YOUR sign-in and YOUR roles:
    - Authentication Administrator (Privileged Authentication Administrator for an admin) to remove MFA methods
    - Cloud Application Administrator or Application Administrator to remove consent grants
    - Exchange Recipient Administrator for inbox rules (only if the ExchangeOnlineManagement module is installed)
  Delegated permissions asked for: User.Read.All, UserAuthenticationMethod.ReadWrite.All,
  DelegatedPermissionGrant.ReadWrite.All, Application.Read.All, User.RevokeSessions.All.

  1. MFA methods: lists every method. Removes only methods whose creation time is on or after -Since (Microsoft
     records it for Authenticator, phone sign-in, passkeys and Windows Hello). Methods without a time are listed
     for you to check with the person.
  2. Consent grants: removes the person's delegated grants to the apps named in -Apps.
  3. Inbox rules: removes the rules named in -InboxRules.
  4. Revokes every sign-in session again, so tokens issued during clean-up stop working.

.EXAMPLE
  .\\Cleanup-F360Incident.ps1          # What if
  .\\Cleanup-F360Incident.ps1 -Run     # does it
#>
#Requires -Version 7.2
[CmdletBinding(SupportsShouldProcess)]
param(
    [switch]$Run,
    [string]$TenantId = ${psq(tid)},
    [string]$User = ${psq(opts.upn)},
    [datetime]$Since = ${psq(new Date(opts.since).toISOString())},
    [string[]]$Apps = @(
${list(opts.apps)}
    ),
    [string[]]$InboxRules = @(
${list(opts.inboxRules)}
    )
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
if (-not $Run) { $WhatIfPreference = $true; Write-Host 'What-if mode: nothing will change. Run again with -Run to do it.' -ForegroundColor Yellow }

if (-not (Get-Module -ListAvailable Microsoft.Graph.Authentication)) { throw 'Install-Module Microsoft.Graph.Authentication -Scope CurrentUser first.' }
$connect = @{ Scopes = @('User.Read.All', 'UserAuthenticationMethod.ReadWrite.All', 'DelegatedPermissionGrant.ReadWrite.All', 'Application.Read.All', 'User.RevokeSessions.All'); NoWelcome = $true; ContextScope = 'Process' }
if ($TenantId) { $connect.TenantId = $TenantId }
Connect-MgGraph @connect
$u = Invoke-MgGraphRequest -Method GET -Uri "/v1.0/users/$([uri]::EscapeDataString($User))?\`$select=id,displayName,userPrincipalName"
Write-Host "Person: $($u.displayName) <$($u.userPrincipalName)>. Incident window starts $($Since.ToUniversalTime().ToString('u'))."

# 1. MFA methods
$paths = @{
    '#microsoft.graph.microsoftAuthenticatorAuthenticationMethod' = 'microsoftAuthenticatorMethods'
    '#microsoft.graph.phoneAuthenticationMethod'                  = 'phoneMethods'
    '#microsoft.graph.fido2AuthenticationMethod'                  = 'fido2Methods'
    '#microsoft.graph.windowsHelloForBusinessAuthenticationMethod' = 'windowsHelloForBusinessMethods'
    '#microsoft.graph.softwareOathAuthenticationMethod'           = 'softwareOathMethods'
    '#microsoft.graph.emailAuthenticationMethod'                  = 'emailMethods'
    '#microsoft.graph.temporaryAccessPassAuthenticationMethod'    = 'temporaryAccessPassMethods'
}
$methods = @((Invoke-MgGraphRequest -Method GET -Uri "/v1.0/users/$($u.id)/authentication/methods").value)
foreach ($m in $methods) {
    $type = $m['@odata.type']; $name = ($m.displayName, $m.phoneNumber, $m.emailAddress, $type | Where-Object { $_ })[0]
    $created = if ($m.ContainsKey('createdDateTime') -and $m.createdDateTime) { [datetime]$m.createdDateTime } else { $null }
    if ($type -eq '#microsoft.graph.passwordAuthenticationMethod') { continue }
    if (-not $created) { Write-Host "MFA method: $name (no creation time; check with the person)"; continue }
    if ($created -lt $Since) { Write-Host "MFA method: $name, added $($created.ToString('u')) (before the incident; kept)"; continue }
    if (-not $paths.ContainsKey($type)) { Write-Warning "MFA method: $name, added during the incident, but this script can't remove $type. Remove it in the Entra admin center."; continue }
    if ($PSCmdlet.ShouldProcess("$name (added $($created.ToString('u')))", 'Remove MFA method added during the incident')) {
        Invoke-MgGraphRequest -Method DELETE -Uri "/v1.0/users/$($u.id)/authentication/$($paths[$type])/$($m.id)" | Out-Null
        Write-Host "Removed MFA method $name."
    }
}

# 2. Consent grants to the apps consented during the incident
if ($Apps.Count) {
    $grants = @((Invoke-MgGraphRequest -Method GET -Uri "/v1.0/users/$($u.id)/oauth2PermissionGrants").value)
    foreach ($g in $grants) {
        $sp = Invoke-MgGraphRequest -Method GET -Uri "/v1.0/servicePrincipals/$($g.clientId)?\`$select=displayName,appId"
        if ($Apps -notcontains $sp.displayName) { continue }
        if ($PSCmdlet.ShouldProcess("$($sp.displayName): $($g.scope)", 'Remove consent grant')) {
            Invoke-MgGraphRequest -Method DELETE -Uri "/v1.0/oauth2PermissionGrants/$($g.id)" | Out-Null
            Write-Host "Removed grant to $($sp.displayName)."
        }
    }
}

# 3. Inbox rules
if ($InboxRules.Count) {
    if (Get-Module -ListAvailable ExchangeOnlineManagement) {
        Connect-ExchangeOnline -ShowBanner:$false -UserPrincipalName (Get-MgContext).Account
        foreach ($r in $InboxRules) {
            if ($PSCmdlet.ShouldProcess("$User / $r", 'Remove inbox rule')) { Remove-InboxRule -Mailbox $User -Identity $r -Confirm:$false; Write-Host "Removed inbox rule $r." }
        }
    } else {
        Write-Warning 'ExchangeOnlineManagement is not installed. Remove these rules in Outlook on the web or the Exchange admin center:'
        $InboxRules | ForEach-Object { Write-Host "  $_" }
    }
}

# 4. Revoke sessions again
if ($PSCmdlet.ShouldProcess($u.userPrincipalName, 'Revoke every sign-in session again')) {
    Invoke-MgGraphRequest -Method POST -Uri "/v1.0/users/$($u.id)/revokeSignInSessions" | Out-Null
    Write-Host 'Sessions revoked.'
}
Write-Host 'Done. In Federation 360 Investigate, click Verify containment.'
`;
}

export interface ContainCheck {
  what: string;
  result: string;
  good: boolean;
}

/** Read-only checks after containment, with the sign-in logs token (Directory.Read.All and AuditLog.Read.All). */
export async function verifyContainment(token: string, upn: string, containedAt: number, fetcher: typeof fetch = fetch): Promise<ContainCheck[]> {
  const get = async (path: string) => {
    const r = await fetcher(`https://graph.microsoft.com${path}`, { headers: { Authorization: `Bearer ${token}` } });
    const j: any = await r.json().catch(() => ({}));
    if (!r.ok) throw new LogsError(classifyGraphError(r.status, j?.error?.code ?? "", j?.error?.message ?? `Graph returned ${r.status}`), j?.error?.message ?? `Graph returned ${r.status}`);
    return j;
  };
  const who = encodeURIComponent(upn);
  const u = await get(`/v1.0/users/${who}?$select=accountEnabled,signInSessionsValidFromDateTime`);
  const since = new Date(containedAt).toISOString().replace(/\.\d{3}Z$/, "Z");
  const filter = encodeURIComponent(`userPrincipalName eq '${upn.replace(/'/g, "''")}' and createdDateTime ge ${since} and status/errorCode eq 0`);
  const s = await get(`/v1.0/auditLogs/signIns?$filter=${filter}&$top=50`);
  const after = (s.value ?? []) as { createdDateTime: string; ipAddress?: string; appDisplayName?: string }[];
  const valid = Date.parse(u.signInSessionsValidFromDateTime ?? "");
  return [
    { what: "Account", result: u.accountEnabled === false ? "Disabled" : "Enabled", good: u.accountEnabled === false },
    {
      what: "Sessions revoked",
      result: Number.isFinite(valid) ? `Sessions valid only from ${new Date(valid).toLocaleString()}` : "Not returned",
      good: Number.isFinite(valid) && valid >= containedAt - 5 * 60_000,
    },
    {
      what: "Successful sign-ins since containment",
      result: after.length ? `${after.length}: ${after.slice(0, 3).map((x) => `${new Date(x.createdDateTime).toLocaleString()} ${x.appDisplayName ?? ""} ${x.ipAddress ?? ""}`.trim()).join("; ")}` : "None",
      good: after.length === 0,
    },
  ];
}
