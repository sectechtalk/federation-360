function Test-Dns {
    param($T, $Settings)
    $sw = [Diagnostics.Stopwatch]::StartNew()
    try {
        $addrs = [Net.Dns]::GetHostAddresses([string]$T.host) | ForEach-Object { $_.IPAddressToString }
        $sw.Stop()
        if (-not $addrs) { return New-Result $T 'fail' 'The name resolved to no addresses.' @{} $sw.ElapsedMilliseconds }
        return New-Result $T 'pass' ('Resolved to {0}' -f (($addrs | Select-Object -First 4) -join ', ')) @{ addresses = @($addrs) } $sw.ElapsedMilliseconds
    } catch {
        $sw.Stop()
        $proxy = Get-ProxyFor ([Uri]('https://' + $T.host + '/'))
        if ($proxy) {
            return New-Result $T 'warn' ('Not resolvable on this device ({0}), but traffic goes through proxy {1}, which resolves it.' -f (Get-ErrorText $_), $proxy.Authority) @{ proxy = $proxy.AbsoluteUri } $sw.ElapsedMilliseconds
        }
        return New-Result $T 'fail' ('DNS lookup failed: {0}' -f (Get-ErrorText $_)) @{} $sw.ElapsedMilliseconds
    }
}

function Test-Tcp {
    param($T, $Settings)
    $port = [int](Get-Prop $T 'port' 443)
    $sw = [Diagnostics.Stopwatch]::StartNew()
    try {
        $c = Connect-Tcp -TargetHost $T.host -Port $port -TimeoutMs $Settings.timeoutMs -Proxy $null
        $remote = $c.Client.RemoteEndPoint.ToString()
        $c.Close(); $sw.Stop()
        return New-Result $T 'pass' ('Connected directly to {0}' -f $remote) @{ remote = $remote; path = 'direct' } $sw.ElapsedMilliseconds
    } catch {
        $direct = Get-ErrorText $_
        $proxy = Get-ProxyFor ([Uri]('https://' + $T.host + '/'))
        if ($proxy) {
            try {
                $c = Connect-Tcp -TargetHost $T.host -Port $port -TimeoutMs $Settings.timeoutMs -Proxy $proxy
                $c.Close(); $sw.Stop()
                return New-Result $T 'pass' ('Direct connection blocked ({0}); reached it through proxy {1}.' -f $direct, $proxy.Authority) @{ path = 'proxy'; proxy = $proxy.AbsoluteUri } $sw.ElapsedMilliseconds
            } catch {
                $sw.Stop()
                return New-Result $T 'fail' ('Direct: {0}. Through proxy {1}: {2}' -f $direct, $proxy.Authority, (Get-ErrorText $_)) @{ proxy = $proxy.AbsoluteUri } $sw.ElapsedMilliseconds
            }
        }
        $sw.Stop()
        return New-Result $T 'fail' $direct @{ path = 'direct' } $sw.ElapsedMilliseconds
    }
}

function Test-Tls {
    param($T, $Settings)
    $port = [int](Get-Prop $T 'port' 443)
    $proxy = Get-ProxyFor ([Uri]('https://' + $T.host + '/'))
    $sw = [Diagnostics.Stopwatch]::StartNew()
    $client = $null; $ssl = $null
    $script:F360PolicyErrors = 'None'
    try {
        $client = Connect-Tcp -TargetHost $T.host -Port $port -TimeoutMs $Settings.timeoutMs -Proxy $proxy
        # Accept every certificate here so the result can say exactly what is wrong; the chain is checked below.
        $cb = [Net.Security.RemoteCertificateValidationCallback] { param($s, $c, $ch, $e) $script:F360PolicyErrors = [string]$e; return $true }
        $ssl = New-Object Net.Security.SslStream($client.GetStream(), $false, $cb)
        $ssl.ReadTimeout = $Settings.timeoutMs; $ssl.WriteTimeout = $Settings.timeoutMs
        $ssl.AuthenticateAsClient([string]$T.host)
        $sw.Stop()
        $cert = New-Object Security.Cryptography.X509Certificates.X509Certificate2($ssl.RemoteCertificate)
        $chain = New-Object Security.Cryptography.X509Certificates.X509Chain
        $chain.ChainPolicy.RevocationMode = 'NoCheck'
        $chainOk = $chain.Build($cert)
        $chainStatus = @($chain.ChainStatus | ForEach-Object { $_.Status.ToString() } | Where-Object { $_ -ne 'NoError' })
        $root = $null
        if ($chain.ChainElements.Count -gt 0) { $root = $chain.ChainElements[$chain.ChainElements.Count - 1].Certificate.Subject }
        $days = [int][Math]::Floor(($cert.NotAfter.ToUniversalTime() - [DateTime]::UtcNow).TotalDays)
        $data = [ordered]@{
            protocol    = $ssl.SslProtocol.ToString()
            subject     = $cert.Subject
            issuer      = $cert.Issuer
            root        = $root
            thumbprint  = $cert.Thumbprint
            notAfter    = $cert.NotAfter.ToUniversalTime().ToString('o')
            daysLeft    = $days
            policyErrors = $script:F360PolicyErrors
            chainStatus = $chainStatus
            path        = $(if ($proxy) { 'proxy' } else { 'direct' })
        }
        $problems = New-Object Collections.Generic.List[string]
        $status = 'pass'
        if ($script:F360PolicyErrors -match 'RemoteCertificateNameMismatch') { $status = 'fail'; $problems.Add("the certificate is not for $($T.host)") }
        if (-not $chainOk -or $script:F360PolicyErrors -match 'RemoteCertificateChainErrors') { $status = 'fail'; $problems.Add('the certificate chain is not trusted on this device (' + (($chainStatus | Select-Object -Unique) -join ', ') + ')') }
        if ($days -lt 0) { $status = 'fail'; $problems.Add("the certificate expired $(-$days) days ago") }
        elseif ($days -le [int]$Settings.certWarnDays -and $status -eq 'pass') { $status = 'warn'; $problems.Add("the certificate expires in $days days") }
        $expect = Get-Prop $T 'expectIssuer' $null
        if ($expect -and ("$($cert.Issuer) $root" -notmatch $expect)) {
            # A trusted chain from an unexpected issuer is the fingerprint of a TLS inspection proxy.
            if ($status -eq 'pass') { $status = 'warn' }
            $problems.Add("issued by '$($cert.Issuer)', not the expected '$expect'. A proxy or security product is probably inspecting TLS; exclude this host from inspection")
            $data.inspected = $true
        }
        if ($data.protocol -match 'Ssl|Tls$|Tls11') { if ($status -eq 'pass') { $status = 'warn' }; $problems.Add("negotiated $($data.protocol); TLS 1.2 or later is required") }
        $detail = if ($problems.Count) { 'Handshake done, but ' + ($problems -join '; ') + '.' } else { "$($data.protocol), issued by $($cert.Issuer), $days days left." }
        return New-Result $T $status $detail $data $sw.ElapsedMilliseconds
    } catch {
        $sw.Stop()
        return New-Result $T 'fail' ('TLS handshake failed: {0}' -f (Get-ErrorText $_)) @{ path = $(if ($proxy) { 'proxy' } else { 'direct' }) } $sw.ElapsedMilliseconds
    } finally {
        if ($ssl) { $ssl.Dispose() }
        if ($client) { $client.Close() }
    }
}

function Invoke-Http {
    param([string]$Url, [string]$Method, [int]$TimeoutMs)
    $req = [Net.HttpWebRequest][Net.WebRequest]::Create($Url)
    $req.Method = $Method
    $req.Timeout = $TimeoutMs; $req.ReadWriteTimeout = $TimeoutMs
    $req.AllowAutoRedirect = $true; $req.MaximumAutomaticRedirections = 5
    $req.UserAgent = "F360-Connectivity/$ScriptVersion"
    $req.UseDefaultCredentials = $false
    $proxy = [Net.WebRequest]::GetSystemWebProxy()
    # Only the proxy gets Windows credentials (for authenticating proxies). Targets get nothing.
    $proxy.Credentials = [Net.CredentialCache]::DefaultCredentials
    $req.Proxy = $proxy
    $resp = $null
    try {
        try { $resp = [Net.HttpWebResponse]$req.GetResponse() }
        catch [Net.WebException] {
            if ($_.Exception.Response) { $resp = [Net.HttpWebResponse]$_.Exception.Response } else { throw }
        }
        $body = ''
        if ($Method -ne 'HEAD') {
            $reader = New-Object IO.StreamReader($resp.GetResponseStream())
            $body = $reader.ReadToEnd()
            $reader.Dispose()
        }
        return [pscustomobject]@{ Status = [int]$resp.StatusCode; Body = $body; Date = $resp.Headers['Date']; FinalUrl = $resp.ResponseUri.AbsoluteUri }
    } finally {
        if ($resp) { $resp.Close() }
    }
}

function Test-Http {
    param($T, $Settings)
    $sw = [Diagnostics.Stopwatch]::StartNew()
    try {
        $r = Invoke-Http -Url $T.url -Method 'GET' -TimeoutMs $Settings.timeoutMs
        $sw.Stop()
        $data = [ordered]@{ status = $r.Status; finalUrl = $r.FinalUrl }
        $expectStatus = @(Get-Prop $T 'expectStatus' @())
        $problems = New-Object Collections.Generic.List[string]
        $status = 'pass'
        if ($expectStatus.Count -gt 0) {
            if ($expectStatus -notcontains $r.Status) { $status = 'fail'; $problems.Add("returned HTTP $($r.Status), expected $($expectStatus -join ' or ')") }
        } elseif ($r.Status -ge 500) {
            $status = 'warn'; $problems.Add("the server answered HTTP $($r.Status) (it is reachable, but erroring)")
        }
        $contains = Get-Prop $T 'expectContains' $null
        if ($contains -and $status -ne 'fail' -and $r.Body.IndexOf([string]$contains, [StringComparison]::OrdinalIgnoreCase) -lt 0) {
            $status = 'fail'; $problems.Add("the response does not contain '$contains' (a proxy block page or captive portal answers like this)")
        }
        $issuer = Get-Prop $T 'expectIssuer' $null
        if ($issuer -and $status -ne 'fail') {
            try {
                $doc = $r.Body | ConvertFrom-Json
                $data.issuer = [string](Get-Prop $doc 'issuer' '')
                if ($data.issuer -ne $issuer) { $status = 'fail'; $problems.Add("issuer is '$($data.issuer)', expected '$issuer'") }
            } catch { $status = 'fail'; $problems.Add('the response is not JSON') }
        }
        $detail = if ($problems.Count) { (($problems -join '; ') + '.') } else { "HTTP $($r.Status) from $($r.FinalUrl)" }
        return New-Result $T $status $detail $data $sw.ElapsedMilliseconds
    } catch {
        $sw.Stop()
        return New-Result $T 'fail' ('Request failed: {0}' -f (Get-ErrorText $_)) @{} $sw.ElapsedMilliseconds
    }
}

function Test-Clock {
    param($T, $Settings)
    $sw = [Diagnostics.Stopwatch]::StartNew()
    try {
        $before = [DateTime]::UtcNow
        $r = Invoke-Http -Url $T.url -Method 'HEAD' -TimeoutMs $Settings.timeoutMs
        $after = [DateTime]::UtcNow
        $sw.Stop()
        if (-not $r.Date) { return New-Result $T 'warn' 'The server sent no Date header, so the clock could not be compared.' @{} $sw.ElapsedMilliseconds }
        $server = [DateTime]::Parse($r.Date, [Globalization.CultureInfo]::InvariantCulture, [Globalization.DateTimeStyles]'AdjustToUniversal,AssumeUniversal')
        $local = $before.AddTicks(($after - $before).Ticks / 2)
        $skew = [int][Math]::Round(($local - $server).TotalSeconds)
        $abs = [Math]::Abs($skew)
        $data = [ordered]@{ skewSeconds = $skew; serverTime = $server.ToString('o'); localTime = $local.ToString('o') }
        $dir = if ($skew -gt 0) { 'ahead of' } else { 'behind' }
        if ($abs -ge [int]$Settings.clockFailSec) { return New-Result $T 'fail' "This device's clock is $abs seconds $dir the identity provider. Tokens and SAML assertions will be rejected as not yet valid or expired. Fix Windows Time sync." $data $sw.ElapsedMilliseconds }
        if ($abs -ge [int]$Settings.clockWarnSec) { return New-Result $T 'warn' "This device's clock is $abs seconds $dir the identity provider." $data $sw.ElapsedMilliseconds }
        return New-Result $T 'pass' "Clock is within $abs seconds of the identity provider." $data $sw.ElapsedMilliseconds
    } catch {
        $sw.Stop()
        return New-Result $T 'fail' ('Could not reach the server to compare clocks: {0}' -f (Get-ErrorText $_)) @{} $sw.ElapsedMilliseconds
    }
}

# ---------------------------------------------------------------------------------------------------------------
# Run
# ---------------------------------------------------------------------------------------------------------------

$started = [DateTime]::UtcNow
try {
    if ($PlanPath) { $planText = Get-Content -LiteralPath $PlanPath -Raw -Encoding UTF8 } else { $planText = $F360EmbeddedPlan }
    $plan = $planText | ConvertFrom-Json
    if ((Get-Prop $plan 'schema' '') -ne 'f360.connectivity.plan/1') { throw "Unknown plan schema '$(Get-Prop $plan 'schema' '')'." }
} catch {
    Write-Output ('F360|v1|error=plan|{0}' -f (Get-ErrorText $_))
    exit 1
}

$s = Get-Prop $plan 'settings' $null
$settings = @{
    timeoutMs    = [int](Get-Prop $s 'timeoutMs' 8000)
    clockWarnSec = [int](Get-Prop $s 'clockWarnSec' 60)
    clockFailSec = [int](Get-Prop $s 'clockFailSec' 300)
    certWarnDays = [int](Get-Prop $s 'certWarnDays' 30)
}

$results = New-Object Collections.Generic.List[object]
foreach ($t in @($plan.tests)) {
    try {
        switch ([string]$t.type) {
            'dns'   { $r = Test-Dns $t $settings }
            'tcp'   { $r = Test-Tcp $t $settings }
            'tls'   { $r = Test-Tls $t $settings }
            'http'  { $r = Test-Http $t $settings }
            'clock' { $r = Test-Clock $t $settings }
            default { $r = New-Result $t 'warn' "Unknown test type '$($t.type)'; update the script." @{} 0 }
        }
    } catch {
        $r = New-Result $t 'fail' ('The test itself failed: {0}' -f (Get-ErrorText $_)) @{} 0
    }
    $r.apps = @(Get-Prop $t 'apps' @())
    $results.Add($r)
}

$os = $null
try { $os = (Get-CimInstance Win32_OperatingSystem -ErrorAction Stop).Caption } catch { }
$counts = [ordered]@{
    pass = @($results | Where-Object { $_.status -eq 'pass' }).Count
    warn = @($results | Where-Object { $_.status -eq 'warn' }).Count
    fail = @($results | Where-Object { $_.status -eq 'fail' }).Count
}
$report = [ordered]@{
    schema        = 'f360.connectivity.result/1'
    scriptVersion = $ScriptVersion
    planId        = [string](Get-Prop $plan 'id' '')
    planName      = [string](Get-Prop $plan 'name' '')
    device        = $env:COMPUTERNAME
    runAs         = [Security.Principal.WindowsIdentity]::GetCurrent().Name
    os            = $os
    psVersion     = $PSVersionTable.PSVersion.ToString()
    startedAt     = $started.ToString('o')
    finishedAt    = [DateTime]::UtcNow.ToString('o')
    proxy         = Get-ProxyInfo
    counts        = $counts
    results       = $results
}
$json = $report | ConvertTo-Json -Depth 8

if ($NoFile) {
    Write-Output $json
} else {
    try {
        if (-not (Test-Path -LiteralPath $OutputDir)) { New-Item -ItemType Directory -Path $OutputDir -Force | Out-Null }
        $file = Join-Path $OutputDir ('{0}-{1}.json' -f $env:COMPUTERNAME, $started.ToString('yyyyMMddTHHmmssZ'))
        [IO.File]::WriteAllText($file, $json, (New-Object Text.UTF8Encoding($false)))
        Get-ChildItem -LiteralPath $OutputDir -Filter '*.json' | Sort-Object LastWriteTime -Descending | Select-Object -Skip $Keep | Remove-Item -Force -ErrorAction SilentlyContinue
    } catch {
        Write-Verbose ('Could not write the result file: {0}' -f (Get-ErrorText $_))
    }
}

# One line for Intune's detection output column (Intune keeps up to 2048 characters).
$bad = @($results | Where-Object { $_.status -ne 'pass' } | Sort-Object { if ($_.status -eq 'fail') { 0 } else { 1 } } | ForEach-Object { '{0}:{1}:{2}' -f $_.status, $_.id, ($_.target -replace '\|', '/') })
$line = 'F360|v1|plan={0}|device={1}|pass={2}|warn={3}|fail={4}|{5}' -f $report.planId, $report.device, $counts.pass, $counts.warn, $counts.fail, ($bad -join ',')
if ($line.Length -gt 2000) { $line = $line.Substring(0, 1997) + '...' }
Write-Output $line

if ($counts.fail -gt 0) { exit 1 } else { exit 0 }
