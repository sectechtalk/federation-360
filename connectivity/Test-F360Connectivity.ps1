# TLS 1.2 (and 1.3 where the OS has it) for HttpWebRequest. Windows PowerShell 5.1 can default to TLS 1.0.
try {
    $proto = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
    try { $proto = $proto -bor [Net.SecurityProtocolType]'Tls13' } catch { }
    [Net.ServicePointManager]::SecurityProtocol = $proto
} catch { }

function New-Result {
    param($Test, [string]$Status, [string]$Detail, [hashtable]$Data, [long]$Ms)
    $label = ''
    if ($Test.PSObject.Properties['label']) { $label = [string]$Test.label }
    $target = ''
    if ($Test.PSObject.Properties['url'] -and $Test.url) { $target = [string]$Test.url }
    elseif ($Test.PSObject.Properties['host'] -and $Test.host) {
        $target = [string]$Test.host
        if ($Test.PSObject.Properties['port'] -and $Test.port) { $target = '{0}:{1}' -f $Test.host, $Test.port }
    }
    if ($null -eq $Data) { $Data = @{} }
    [ordered]@{
        id     = [string]$Test.id
        type   = [string]$Test.type
        label  = $label
        target = $target
        status = $Status
        ms     = $Ms
        detail = $Detail
        data   = $Data
    }
}

function Get-Prop {
    param($Object, [string]$Name, $Default)
    if ($null -ne $Object -and $Object.PSObject.Properties[$Name] -and $null -ne $Object.$Name) { return $Object.$Name }
    return $Default
}

function Get-ErrorText {
    param($Err)
    $e = $Err.Exception
    while ($e.InnerException) { $e = $e.InnerException }
    return $e.Message
}

# The proxy Windows would use for this URL: WinINet/IE settings in user context, WinHTTP for SYSTEM falls back to direct.
function Get-ProxyFor {
    param([Uri]$Uri)
    try {
        $p = [Net.WebRequest]::GetSystemWebProxy()
        if ($p.IsBypassed($Uri)) { return $null }
        $u = $p.GetProxy($Uri)
        if ($null -eq $u -or $u.Host -eq $Uri.Host) { return $null }
        return $u
    } catch { return $null }
}

function Get-ProxyInfo {
    $info = [ordered]@{ user = $null; winhttp = $null; pac = $null; runAs = [Security.Principal.WindowsIdentity]::GetCurrent().Name }
    try {
        $ie = Get-ItemProperty -Path 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Internet Settings' -ErrorAction Stop
        if ((Get-Prop $ie 'ProxyEnable' 0) -eq 1) { $info.user = [string](Get-Prop $ie 'ProxyServer' '') }
        $pac = Get-Prop $ie 'AutoConfigURL' $null
        if ($pac) { $info.pac = [string]$pac }
    } catch { }
    try {
        $raw = (Get-ItemProperty -Path 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Internet Settings\Connections' -Name WinHttpSettings -ErrorAction Stop).WinHttpSettings
        # Byte 8 holds the flags; 3 = proxy set. Then length-prefixed proxy server string.
        if ($raw -and $raw.Length -gt 16 -and ($raw[8] -band 2)) {
            $len = [BitConverter]::ToInt32($raw, 12)
            if ($len -gt 0 -and (16 + $len) -le $raw.Length) { $info.winhttp = [Text.Encoding]::ASCII.GetString($raw, 16, $len) }
        }
    } catch { }
    return $info
}

function Connect-Tcp {
    # Returns an open TcpClient to Host:Port, directly or through an HTTP proxy CONNECT tunnel.
    param([string]$TargetHost, [int]$Port, [int]$TimeoutMs, [Uri]$Proxy)
    $client = New-Object Net.Sockets.TcpClient
    $connectHost = $TargetHost; $connectPort = $Port
    if ($Proxy) { $connectHost = $Proxy.Host; $connectPort = $Proxy.Port }
    $ar = $client.BeginConnect($connectHost, $connectPort, $null, $null)
    if (-not $ar.AsyncWaitHandle.WaitOne($TimeoutMs)) {
        $client.Close()
        throw ('Timed out after {0} ms connecting to {1}:{2}' -f $TimeoutMs, $connectHost, $connectPort)
    }
    $client.EndConnect($ar)
    $client.ReceiveTimeout = $TimeoutMs; $client.SendTimeout = $TimeoutMs
    if ($Proxy) {
        $stream = $client.GetStream()
        $req = "CONNECT {0}:{1} HTTP/1.1`r`nHost: {0}:{1}`r`n`r`n" -f $TargetHost, $Port
        $bytes = [Text.Encoding]::ASCII.GetBytes($req)
        $stream.Write($bytes, 0, $bytes.Length)
        $buf = New-Object byte[] 1
        $sb = New-Object Text.StringBuilder
        while (-not $sb.ToString().EndsWith("`r`n`r`n")) {
            if ($stream.Read($buf, 0, 1) -le 0) { break }
            [void]$sb.Append([char]$buf[0])
            if ($sb.Length -gt 8192) { break }
        }
        $first = ($sb.ToString() -split "`r`n")[0]
        if ($first -notmatch '^HTTP/1\.[01] 200') {
            $client.Close()
            throw ('Proxy {0} refused CONNECT to {1}:{2}: {3}' -f $Proxy.Authority, $TargetHost, $Port, $first)
        }
    }
    return $client
}

