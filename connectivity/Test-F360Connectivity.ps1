<#
.SYNOPSIS
    Federation 360 agentless connectivity test. Checks, from a real Windows device, that it can reach the
    identity provider and app endpoints its sign-ins depend on.

.DESCRIPTION
    Built for Windows PowerShell 5.1 with no modules, so it runs as an Intune Remediations detection script
    delivered and signed through Remediation 360. It installs nothing, starts nothing in the background and
    sends no credentials or tokens anywhere. It only makes anonymous DNS lookups, TCP connects, TLS handshakes
    and HTTP GET/HEAD requests to the targets in its test plan.

    The test plan is generated by the Federation 360 "Connectivity test" page and embedded between the
    F360 PLAN markers below, so the signed script and its plan travel together. -PlanPath overrides it for
    a manual run.

    Output:
      - A JSON result file in -OutputDir (default C:\ProgramData\F360\results), newest -Keep files kept.
        Load it on the Federation 360 Connectivity test page.
      - One summary line on stdout starting with F360| (Intune shows it as the detection output).
      - Exit code 1 when any test failed (Intune reports "With issues"), otherwise 0.

.PARAMETER PlanPath
    Use this plan file instead of the embedded plan.

.PARAMETER OutputDir
    Folder for the JSON result files.

.PARAMETER Keep
    How many result files to keep in OutputDir. Older ones are deleted.

.PARAMETER NoFile
    Do not write a result file. The JSON is printed instead, before the summary line.

.EXAMPLE
    powershell.exe -ExecutionPolicy Bypass -File .\Test-F360Connectivity.ps1 -PlanPath .\f360-plan.json -OutputDir .\results
#>
[CmdletBinding()]
param(
    [string]$PlanPath,
    [string]$OutputDir = (Join-Path $env:ProgramData 'F360\results'),
    [ValidateRange(1, 500)][int]$Keep = 20,
    [switch]$NoFile
)

